"""Prepare compact 1280x720 arena images from preserved user-supplied PNGs.

Only size, a sub-pixel aspect crop and WebP encoding change. Original image
bytes are preserved and verified against the intake checksums before every build.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT=Path(__file__).resolve().parent.parent

def main():
    intake=json.loads((ROOT/'artwork/arenas/intake.json').read_text())
    catalog=json.loads((ROOT/'artwork/arenas/catalog.json').read_text())
    sources={e['id']:e for e in intake['images']}
    output=ROOT/'browser/assets/arenas';output.mkdir(parents=True,exist_ok=True)
    metadata={};arenas=[]
    for arena in catalog:
        entry=sources[arena['id']]
        source=ROOT/'artwork/arenas/source'/entry['originalName']
        if hashlib.sha256(source.read_bytes()).hexdigest()!=entry['sha256']:
            raise ValueError('Arena original changed: '+entry['originalName'])
        with Image.open(source) as image:
            image=ImageOps.fit(image.convert('RGB'),(1280,720),method=Image.Resampling.LANCZOS)
            target=output/(arena['id']+'.webp')
            image.save(target,'WEBP',quality=90,method=4)
        metadata[arena['id']]={'originalName':entry['originalName'],'sourceSha256':entry['sha256'],
                             'width':1280,'height':720,'bytes':target.stat().st_size,
                             'sha256':hashlib.sha256(target.read_bytes()).hexdigest()}
        arenas.append({**arena,'sourceName':entry['originalName'],'sourceSha256':entry['sha256']})
        print(arena['id'],target.stat().st_size,'bytes',flush=True)
    (output/'metadata.json').write_text(json.dumps(metadata,indent=2)+'\n')
    js="// Generated by tools/prepare-arena-art.py from the reviewed arena catalog.\n"
    js+="(function(root){'use strict';const ARENAS="+json.dumps(arenas,separators=(',',':'),ensure_ascii=False)+";const api={ARENAS};root.NationArenaCatalog=api;if(typeof module!=='undefined'&&module.exports)module.exports=api;})(typeof window!=='undefined'?window:globalThis);\n"
    (ROOT/'browser/src/arena-catalog.js').write_text(js)
    print('Prepared',len(metadata),'arena images;',sum(e['bytes'] for e in metadata.values()),'runtime bytes')

if __name__=='__main__':main()
